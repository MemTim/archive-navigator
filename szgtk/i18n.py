LANG_RU = False
RU = {}  # заполняется ниже


def _system_is_ru():
    loc = (os.environ.get('LC_ALL') or os.environ.get('LC_MESSAGES') or
           os.environ.get('LANG') or '').lower()
    return loc.startswith('ru')


def set_language(code):
    """code: auto | en | ru"""
    global LANG_RU
    LANG_RU = _system_is_ru() if code == 'auto' else (code == 'ru')


def _(s):
    return RU.get(s, s) if LANG_RU else s


def N_(s):
    """Маркер строки для перевода «на потом» (переводится в момент показа)."""
    return s


def _early_language():
    try:
        with open(CONF_FILE, encoding='utf-8') as f:
            return json.load(f).get('language', 'auto')
    except (OSError, ValueError):
        return 'auto'


